// Release signing — keystore.properties and the keystore itself are gitignored, never
// committed. Debug builds and CI without the keystore still work; only bundleRelease/
// assembleRelease need it, and fail loudly (missing signingConfig) rather than silently
// producing an unsigned/differently-signed build if it's absent.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties()
if (keystorePropertiesFile.exists()) {
    keystoreProperties.load(keystorePropertiesFile.inputStream())
}

android {
    namespace = "com.stevenroot.mabibliotheque"
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        applicationId = "com.stevenroot.mabibliotheque"
        // User confirmed target devices are Android 13+ only — no need for the
        // minSdk=30/custom-AppLocale workaround used in TWP_Inventaire.
        minSdk = 33
        targetSdk = 37
        versionCode = 4
        versionName = "1.3"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (keystorePropertiesFile.exists()) {
            create("release") {
                storeFile = file(keystoreProperties["storeFile"] as String)
                storePassword = keystoreProperties["storePassword"] as String
                keyAlias = keystoreProperties["keyAlias"] as String
                keyPassword = keystoreProperties["keyPassword"] as String
            }
        }
    }

    buildTypes {
        release {
            optimization {
                enable = false
            }
            if (keystorePropertiesFile.exists()) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
    buildFeatures {
        compose = true
    }
}

